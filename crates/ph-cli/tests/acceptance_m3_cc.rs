//! M3/T10 acceptance: controller lanes, **through MCP only**.
//!
//! A scripted agent drives `patternhaus-cli mcp --headless` over stdio and:
//!
//! 1. imports a generated one-region SFZ string patch (a sustained tone, 24 dB down), and routes
//!    CC1 (mod wheel) to the sampler's volume, +24 dB at full travel (`sampler.modulation_set`):
//!    the way a hosted orchestral library takes its dynamics from the mod wheel;
//! 2. writes one 4-second sustained note and shapes a CC1 swell over it with `cc.shape`
//!    (0.1 -> 1.0 -> 0.1); reads the musical diff, `cc.list`, the pattern view and the
//!    piano-roll snapshot with its lane strip;
//! 3. renders it, then clears the lane and renders again, then undoes the clear.
//!
//! Checks: the render's level rises and falls with the swell (measured in 100 ms windows: the
//! middle is more than 8 times the start and the end, about 21 dB); without the lane the same
//! note stays quiet; undo brings the identical render back; the exported file matches the
//! offline oracle bit for bit, and a real-time engine on a simulated device matches the
//! offline render.

mod common;

use common::*;
use ph_engine::assets::FileResolver;
use ph_engine::{AudioBuffer, Engine, EngineConfig, PlayMode, RenderSettings, TransportCommand};
use serde_json::{Value, json};
use std::path::{Path, PathBuf};
use std::sync::Arc;

const SR: u32 = 48_000;
const BPM: f64 = 120.0;
/// Four seconds at 120 BPM: two bars of 3840 ticks.
const NOTE: u64 = 7680;

fn first_difference(a: &[Vec<f32>], b: &[Vec<f32>]) -> Option<(usize, usize)> {
    for c in 0..2 {
        if a[c].len() != b[c].len() {
            return Some((c, usize::MAX));
        }
        if let Some(i) = (0..a[c].len()).find(|&i| a[c][i].to_bits() != b[c][i].to_bits()) {
            return Some((c, i));
        }
    }
    None
}

/// A steady string-like tone at C4, long enough for the note and its release.
fn write_patch(dir: &Path) -> PathBuf {
    std::fs::create_dir_all(dir).unwrap();
    let n = 6 * SR as usize;
    let x: Vec<f32> = (0..n)
        .map(|i| {
            let t = i as f64 / SR as f64;
            let v: f64 = (1..=4)
                .map(|h| (std::f64::consts::TAU * 261.625_565 * h as f64 * t).sin() / h as f64)
                .sum();
            (v * 0.3 * (t / 0.05).min(1.0)) as f32
        })
        .collect();
    ph_formats::encode::write_wav(
        &dir.join("tone.wav"),
        &[x],
        SR,
        ph_formats::encode::WavFormat::Float32,
    )
    .unwrap();
    let sfz = dir.join("tone.sfz");
    std::fs::write(
        &sfz,
        "// generated by the M3 controller lanes acceptance test\n\
         <global> pitch_keycenter=60\n\
         <group> lokey=36 hikey=84 volume=-24 ampeg_release=0.3\n\
         <region> sample=tone.wav\n",
    )
    .unwrap();
    sfz
}

async fn render(c: &Client, name: &str) -> (PathBuf, Vec<Vec<f32>>) {
    let r = ok(
        c,
        "render",
        json!({ "name": name, "format": "wav", "bit_depth": 32 }),
    )
    .await;
    let path = PathBuf::from(r["path"].as_str().unwrap());
    let audio = ph_formats::decode::decode_file(&path).unwrap();
    assert_eq!(audio.sample_rate as u32, SR);
    (path, audio.channels)
}

/// RMS of the 100 ms window starting at `secs`.
fn level(x: &[Vec<f32>], secs: f64) -> f64 {
    let a = (secs * SR as f64) as usize;
    let w = &x[0][a..a + 4800];
    (w.iter().map(|v| (*v as f64).powi(2)).sum::<f64>() / w.len() as f64).sqrt()
}

fn db(v: f64) -> f64 {
    20.0 * v.max(1e-9).log10()
}

#[tokio::test(flavor = "multi_thread")]
async fn m3_cc_lanes_acceptance_a_cc1_swell_shapes_a_sampler_amplitude_through_mcp_only() {
    let dir = tempfile::tempdir().unwrap();
    let song = dir.path().join("song");
    let sfz = write_patch(&song.join("incoming/tone"));
    let c = connect(&song, &[]).await;

    // ---- 1. an instrument whose volume follows the mod wheel ---------------------------------
    ok(&c, "set_tempo", json!({ "bpm": BPM })).await;
    let imp = ok(
        &c,
        "run",
        json!({ "id": "sampler.import", "params": { "path": sfz.to_string_lossy(), "collect": true } }),
    )
    .await;
    let (inst, ch) = (id(&imp, "instrument"), id(&imp, "channel"));
    ok(
        &c,
        "run",
        json!({ "id": "sampler.modulation_set", "params": { "instrument": inst, "routes": [
            { "source": { "kind": "cc", "controller": 1 }, "target": "volume", "depth": 24.0 }] } }),
    )
    .await;

    // ---- 2. one sustained note and a CC1 swell over it -----------------------------------------
    let pat = id(
        &ok(
            &c,
            "run",
            json!({ "id": "pattern.add", "params": { "name": "Swell" } }),
        )
        .await,
        "pattern",
    );
    ok(
        &c,
        "run",
        json!({ "id": "note.add", "params": { "pattern": pat, "channel": ch,
            "notes": [{ "key": 60, "start": 0, "length": NOTE, "velocity": 0.8 }] } }),
    )
    .await;
    ok(
        &c,
        "run",
        json!({ "id": "playlist.add_clip", "params": { "track": 0, "pattern": pat, "start": 0 } }),
    )
    .await;
    // the controller list is part of the command's schema: agents find it by name
    let described = ok(&c, "describe_command", json!({ "id": "cc.shape" })).await;
    assert!(described.to_string().contains("mod wheel"), "{described}");
    let shaped = ok(
        &c,
        "run",
        json!({ "id": "cc.shape", "params": { "pattern": pat, "channel": ch,
            "controller": "mod wheel", "start": 0, "end": NOTE,
            "from": 0.1, "peak": 1.0, "to": 0.1 } }),
    )
    .await;
    let r = &shaped["results"][0]["result"];
    assert_eq!(r["shape"], "swell 0.1→1→0.1", "{shaped}");
    assert_eq!(r["points"].as_array().unwrap().len(), 3);
    assert!(r["warning"].is_null(), "{shaped}");
    let diff = shaped["changes"].to_string();
    assert!(
        diff.contains("CC1 Mod Wheel on tone in Swell, bars 1-2: swell 0.1→1→0.1"),
        "{diff}"
    );
    // what the agent can read back
    let list = ok(
        &c,
        "run",
        json!({ "id": "cc.list", "params": { "pattern": pat } }),
    )
    .await;
    assert_eq!(
        list["results"][0]["result"]["lanes"][0]["label"],
        "CC1 Mod Wheel"
    );
    let view = ok(
        &c,
        "get_state",
        json!({ "view": "pattern", "args": { "pattern": "Swell" } }),
    )
    .await;
    assert!(
        view["channels"][0]["lanes"][0]
            .as_str()
            .unwrap()
            .starts_with("CC1 Mod Wheel: swell 0.1→1→0.1"),
        "{view}"
    );
    let with_strip = call(
        &c,
        "snapshot",
        json!({ "kind": "piano_roll", "pattern": "Swell" }),
    )
    .await;
    let without_strip = call(
        &c,
        "snapshot",
        json!({ "kind": "piano_roll", "pattern": "Swell", "lanes": false }),
    )
    .await;
    assert!(!with_strip.is_error && !without_strip.is_error);
    assert!(
        with_strip
            .texts
            .join(" ")
            .contains("controller lanes below: CC1 Mod Wheel")
    );
    let (_, h_with) = assert_png(&with_strip.images[0], 480);
    let (_, h_without) = assert_png(&without_strip.images[0], 480);
    assert!(
        h_with > h_without + 40,
        "the lane strip is drawn: {h_without} -> {h_with}"
    );

    // ---- 3. hear it: the level follows the swell --------------------------------------------------
    let (_, swell) = render(&c, "swell").await;
    let (start, mid, end) = (
        level(&swell, 0.05),
        level(&swell, 1.95),
        level(&swell, 3.85),
    );
    println!(
        "M3 controller lanes: start {:.1} dBFS, middle {:.1} dBFS, end {:.1} dBFS (rise {:.1} dB, fall {:.1} dB)",
        db(start),
        db(mid),
        db(end),
        db(mid) - db(start),
        db(mid) - db(end)
    );
    assert!(mid > 8.0 * start, "the swell rises: {start} -> {mid}");
    assert!(mid > 8.0 * end, "and falls: {mid} -> {end}");
    // the loudest window sits near the middle of the note
    let loudest = (0..38)
        .map(|k| (k, level(&swell, k as f64 * 0.1)))
        .max_by(|a, b| a.1.total_cmp(&b.1))
        .unwrap()
        .0;
    assert!(
        (15..=23).contains(&loudest),
        "peak at {} s",
        loudest as f64 / 10.0
    );

    // without the lane the same note stays at the instrument's quiet default
    ok(
        &c,
        "run",
        json!({ "id": "cc.clear", "params": { "pattern": pat, "channel": ch } }),
    )
    .await;
    let (_, flat) = render(&c, "flat").await;
    let flat_mid = level(&flat, 1.95);
    println!(
        "M3 controller lanes: without the lane the middle is {:.1} dBFS",
        db(flat_mid)
    );
    assert!(
        flat_mid * 8.0 < mid,
        "no lane, no swell: {flat_mid} vs {mid}"
    );
    // undo brings the swell, and the render, back exactly
    ok(&c, "undo_mine", json!({})).await;
    let (_, again) = render(&c, "again").await;
    assert_eq!(
        first_difference(&again, &swell),
        None,
        "undo restores the render"
    );
    ok(&c, "run", json!({ "id": "file.save" })).await;
    let (wav, saved) = render(&c, "acceptance-m3-cc").await;
    assert_eq!(first_difference(&saved, &swell), None);
    drop(c);

    // ---- the export matches the offline oracle, and so does the live engine ------------------------
    let project = ph_formats::load_project(&song).unwrap();
    assert_eq!(project.patterns.values().next().unwrap().cc_count(), 3);
    let assets = FileResolver::new()
        .with_assets_dir(Path::new(env!("CARGO_MANIFEST_DIR")).join("../../assets"))
        .with_project_dir(&song);
    assert!(
        ph_engine::project_warnings(&project, &assets).is_empty(),
        "{:?}",
        ph_engine::project_warnings(&project, &assets)
    );
    let settings = |tail: bool, block: usize| RenderSettings {
        mode: PlayMode::Song,
        range: None,
        sample_rate: SR,
        quality: ph_node::Quality::Live,
        include_tail: tail,
        block_frames: block,
    };
    let oracle = ph_engine::render_offline(&project, &settings(true, 256), &assets).unwrap();
    let exported = ph_formats::decode::decode_file(&wav).unwrap();
    assert_eq!(
        first_difference(&exported.channels, &oracle.channels),
        None,
        "the exported WAV differs from the offline oracle (channel, frame)"
    );
    let song_only = ph_engine::render_offline(&project, &settings(false, 512), &assets).unwrap();
    let (engine, mut dev) = Engine::start_simulated(
        EngineConfig {
            sample_rate: SR,
            buffer_frames: 256,
            ..EngineConfig::default()
        },
        Arc::new(assets),
    )
    .unwrap();
    engine.set_project(Arc::new(project.clone())).unwrap();
    engine.transport(TransportCommand::Play);
    let mut rt: Vec<Vec<f32>> = vec![Vec::new(), Vec::new()];
    while rt[0].len() < song_only.frames() {
        let AudioBuffer { channels, .. } = dev.pull(256);
        rt[0].extend_from_slice(&channels[0]);
        rt[1].extend_from_slice(&channels[1]);
    }
    rt[0].truncate(song_only.frames());
    rt[1].truncate(song_only.frames());
    assert_eq!(
        first_difference(&rt, &song_only.channels),
        None,
        "real-time output differs from the offline render (channel, frame)"
    );
    assert!(engine.stats().warnings.is_empty());
    assert_eq!(engine.stats().underruns, 0);
    let _: Value = json!(null);
}
