pub const GLYPH_W: u32 = 5;
pub const GLYPH_H: u32 = 7;

fn glyph(c: char) -> Option<&'static [&'static str; 7]> {
    let c = c.to_ascii_uppercase();
    GLYPHS.iter().find(|(g, _)| *g == c).map(|(_, rows)| rows)
}

/// Width in pixels of `s` at `scale`.
pub fn width(s: &str, scale: u32) -> u32 {
    let n = s.chars().count() as u32;
    if n == 0 {
        0
    } else {
        n * (GLYPH_W + 1) * scale - scale
    }
}

pub fn height(scale: u32) -> u32 {
    GLYPH_H * scale
}

pub fn fill(pm: &mut Pixmap, x: f32, y: f32, w: f32, h: f32, c: Color) {
    if let Some(r) = Rect::from_xywh(x, y, w.max(0.0), h.max(0.0)) {
        let mut p = Paint::default();
        p.set_color(c);
        p.anti_alias = false;
        pm.fill_rect(r, &p, Transform::identity(), None);
    }
}

/// Draws `s` with its top-left at `(x, y)`.
pub fn draw(pm: &mut Pixmap, s: &str, x: i32, y: i32, scale: u32, c: Color) {
    let mut cx = x;
    for ch in s.chars() {
        if let Some(rows) = glyph(ch) {
            for (ry, row) in rows.iter().enumerate() {
                for (rx, b) in row.bytes().enumerate() {
                    if b == b'#' {
                        fill(
                            pm,
                            (cx + (rx as u32 * scale) as i32) as f32,
                            (y + (ry as u32 * scale) as i32) as f32,
                            scale as f32,
                            scale as f32,
                            c,
                        );
                    }
                }
            }
        }
        cx += ((GLYPH_W + 1) * scale) as i32;
    }
}

/// Draws `s` so its right edge is at `x`, vertically centred on `y`.
pub fn draw_right(pm: &mut Pixmap, s: &str, x: i32, y: i32, scale: u32, c: Color) {
    let w = width(s, scale) as i32;
    draw(pm, s, x - w, y - (height(scale) / 2) as i32, scale, c);
}

/// Draws `s` centred on `x`, with its top at `y`.
pub fn draw_centered(pm: &mut Pixmap, s: &str, x: i32, y: i32, scale: u32, c: Color) {
    let w = width(s, scale) as i32;
    draw(pm, s, x - w / 2, y, scale, c);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_five_wide() {
        for (c, rows) in GLYPHS {
            for r in rows {
                assert_eq!(r.len(), 5, "{c}");
            }
        }
        for c in "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ#.-/: ".chars() {
            assert!(c == ' ' || glyph(c).is_some(), "{c}");
        }
    }
}
