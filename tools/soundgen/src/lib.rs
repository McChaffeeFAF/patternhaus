//! Patternhaus factory sound generator (DESIGN section 7). Not shipped.
//!
//! `cargo run -p soundgen -- render` writes every factory WAV and `assets/PROVENANCE.toml`;
//! `check` re-renders into a temporary folder and fails if `assets/` differs; `report`
//! prints the quality measurements. Output is byte-identical on every platform: all
//! randomness is seeded and all transcendental math is in [`dmath`].

#![allow(clippy::needless_range_loop)]

pub mod dmath;
pub mod dsp;
pub mod measure;
pub mod recipes;
pub mod voices;

use recipes::Recipe;
use std::io::Cursor;
use std::path::{Path, PathBuf};

/// The repository's `assets/` folder.
pub fn assets_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../assets")
}

/// 48 kHz, 24-bit, mono WAV.
pub fn wav_bytes(samples: &[i32]) -> Vec<u8> {
    let spec = hound::WavSpec {
        channels: 1,
        sample_rate: 48_000,
        bits_per_sample: 24,
        sample_format: hound::SampleFormat::Int,
    };
    let mut buf = Cursor::new(Vec::new());
    let mut w = hound::WavWriter::new(&mut buf, spec).expect("wav header");
    for s in samples {
        w.write_sample(*s).expect("wav sample");
    }
    w.finalize().expect("wav finalize");
    buf.into_inner()
}

/// The finished integer samples of a recipe.
pub fn render_i24(r: &Recipe) -> Vec<i32> {
    dsp::to_i24(&r.render())
}

fn rel_path(p: &Path, root: &Path) -> String {
    p.strip_prefix(root)
        .unwrap()
        .to_string_lossy()
        .replace('\\', "/")
}

/// All files under `dir`, as paths relative to `root`.
fn walk(dir: &Path, root: &Path, out: &mut Vec<String>) -> std::io::Result<()> {
    let Ok(rd) = std::fs::read_dir(dir) else {
        return Ok(());
    };
    for e in rd {
        let p = e?.path();
        if p.is_dir() {
            walk(&p, root, out)?;
        } else {
            out.push(rel_path(&p, root));
        }
    }
    Ok(())
}

/// Files under `assets/` that soundgen does not generate (presets, README), sorted.
fn hand_authored(assets: &Path) -> std::io::Result<Vec<String>> {
    let mut v = Vec::new();
    walk(assets, assets, &mut v)?;
    v.retain(|r| !r.starts_with("samples/") && r != "PROVENANCE.toml");
    v.sort();
    Ok(v)
}

/// The complete `PROVENANCE.toml` text.
pub fn provenance_toml(recipes: &[Recipe], hand: &[String]) -> String {
    let mut s = String::from(
        "# Provenance for every file under assets/ (DESIGN section 7).\n\
         # Generated by `cargo run -p soundgen -- render`; do not edit by hand.\n\
         # Everything generated is dedicated to the public domain (CC0-1.0).\n",
    );
    for r in recipes {
        s.push_str(&format!(
            "\n[[file]]\npath = \"{}\"\nlicense = \"CC0-1.0\"\ngenerator = \"soundgen {} {}\"\n",
            r.asset_path(),
            r.name,
            r.params_hash()
        ));
    }
    for h in hand {
        s.push_str(&format!(
            "\n[[file]]\npath = \"{h}\"\nlicense = \"CC0-1.0\"\nsource = \"hand-authored, Patternhaus contributors\"\n"
        ));
    }
    s
}

/// Write every generated file (and the provenance table) under `out`. Hand-authored files
/// are discovered in `assets`.
pub fn render_all(out: &Path, assets: &Path) -> std::io::Result<()> {
    let recipes = recipes::all();
    for r in &recipes {
        let path = out.join(r.asset_path());
        std::fs::create_dir_all(path.parent().unwrap())?;
        std::fs::write(path, wav_bytes(&render_i24(r)))?;
    }
    std::fs::write(
        out.join("PROVENANCE.toml"),
        provenance_toml(&recipes, &hand_authored(assets)?),
    )
}

/// Re-render into a temporary folder and compare with `assets`. Returns the number of
/// identical generated files.
pub fn check(assets: &Path) -> Result<usize, Vec<String>> {
    let io = |e: std::io::Error| vec![e.to_string()];
    let tmp = tempfile::tempdir().map_err(io)?;
    render_all(tmp.path(), assets).map_err(io)?;
    let mut fresh_files = Vec::new();
    walk(tmp.path(), tmp.path(), &mut fresh_files).map_err(io)?;
    let mut errors = Vec::new();
    for rel in &fresh_files {
        let fresh = std::fs::read(tmp.path().join(rel)).map_err(io)?;
        match std::fs::read(assets.join(rel)) {
            Ok(old) if old == fresh => {}
            Ok(_) => errors.push(format!("assets/{rel} differs from a fresh render")),
            Err(_) => errors.push(format!("assets/{rel} is missing")),
        }
    }
    let mut on_disk = Vec::new();
    walk(&assets.join("samples"), assets, &mut on_disk).map_err(io)?;
    for rel in on_disk {
        if !fresh_files.contains(&rel) {
            errors.push(format!("assets/{rel} is not produced by any recipe"));
        }
    }
    if errors.is_empty() {
        Ok(fresh_files.len())
    } else {
        errors.sort();
        Err(errors)
    }
}
